#!/usr/bin/env python3
"""Regenerate sinker.obj, the model of the catalog case edm/sinker (#2872).

The part is a clean-room Camcraft fixture: a 60 x 40 x 25 mm block of
hardened die steel with one blind rectangular cavity, 20 x 12 mm and 8 mm
deep (floor at z = 17), centred at (5, 0). A sinker EDM burns the cavity
with a rectangular electrode, so its walls are sharp and vertical: the
shape a milling cutter cannot leave in the corners.

Method: the solid is the block minus the cavity box. Both boxes have faces
on one plane set, so the boundary is built exactly by voxel CSG over that
grid: every inside/outside cell face is emitted as a unit quad. Unit quads
tile every plane the same way from both sides, so the mesh is conforming
(no T-junctions), watertight, and consistently outward-oriented; the
script self-checks that before writing.

Usage: python gen_sinker_obj.py [output.obj]
"""

import sys

BLOCK = (-30.0, 30.0, -20.0, 20.0, 0.0, 25.0)   # x0 x1 y0 y1 z0 z1
CAVITY = (-5.0, 15.0, -6.0, 6.0, 17.0, 25.0)

XS = [-30.0, -5.0, 15.0, 30.0]
YS = [-20.0, -6.0, 6.0, 20.0]
ZS = [0.0, 17.0, 25.0]
PLANES = [XS, YS, ZS]


def inside_box(p, box):
    x0, x1, y0, y1, z0, z1 = box
    return x0 <= p[0] <= x1 and y0 <= p[1] <= y1 and z0 <= p[2] <= z1


def solid(p):
    return inside_box(p, BLOCK) and not inside_box(p, CAVITY)


def build():
    dims = [len(p) - 1 for p in PLANES]
    inside = set()
    for i in range(dims[0]):
        for j in range(dims[1]):
            for k in range(dims[2]):
                mid = [(PLANES[a][idx] + PLANES[a][idx + 1]) / 2
                       for a, idx in enumerate((i, j, k))]
                if solid(tuple(mid)):
                    inside.add((i, j, k))

    groups = {}
    for cell in inside:
        for axis in range(3):
            for sign in (+1, -1):
                nxt = list(cell)
                nxt[axis] += sign
                if tuple(nxt) in inside:
                    continue
                plane = cell[axis] + (1 if sign > 0 else 0)
                a, b = (d for d in range(3) if d != axis)
                groups.setdefault((axis, plane, sign, a, b), set()).add(
                    (cell[a], cell[b]))

    # with a, b the other two axes in ascending order, walking (a then b)
    # gives a normal of +axis for axis 0 and 2 and -axis for axis 1
    # (hat{x} x hat{z} = -hat{y}), so check that sign before emitting
    WALK_SIGN = {0: +1, 1: -1, 2: +1}
    quads = []  # each a list of 4 (x, y, z) coordinate tuples, oriented
    for (axis, plane, sign, a, b), cells in sorted(groups.items()):
        for (ca, cb) in sorted(cells):
            quad = []
            for p, q in [(ca, cb), (ca + 1, cb), (ca + 1, cb + 1), (ca, cb + 1)]:
                pos = [None, None, None]
                pos[axis] = PLANES[axis][plane]
                pos[a] = PLANES[a][p]
                pos[b] = PLANES[b][q]
                quad.append(tuple(pos))
            if WALK_SIGN[axis] != sign:
                quad.reverse()
            quads.append(quad)
    return quads


def check(quads):
    """Watertight and consistently oriented: every directed edge appears
    exactly once and its reverse appears exactly once."""
    seen = {}
    for quad in quads:
        for p, q in zip(quad, quad[1:] + quad[:1]):
            if p == q:
                raise SystemExit("degenerate quad: %r" % (quad,))
            if (p, q) in seen:
                raise SystemExit("directed edge reused: %r -> %r" % (p, q))
            seen[(p, q)] = True
    for (p, q) in seen:
        if (q, p) not in seen:
            raise SystemExit("open edge: %r -> %r" % (p, q))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "sinker.obj"
    quads = build()
    check(quads)

    vid = {}
    vlines = []
    for quad in quads:
        for p in quad:
            if p not in vid:
                vid[p] = len(vlines) + 1
                vlines.append("v %g %g %g" % p)
    flines = []
    for quad in quads:
        flines.append("f " + " ".join(str(vid[p]) for p in quad))

    with open(out, "w", newline="\n") as fh:
        fh.write(HEADER)
        fh.write("\n" + "\n".join(vlines) + "\n\n" + "\n".join(flines) + "\n")
    print("wrote %s: %d vertices, %d faces" % (out, len(vlines), len(flines)))


HEADER = """\
# Camcraft catalog case edm/sinker: a 60 x 40 x 25 mm block with one blind
# rectangular cavity, 20 x 12 mm and 8 mm deep (floor z = 17), centred at
# (5, 0), for a sinker EDM burn. Authored for this repository (clean-room
# fixture); generated by gen_sinker_obj.py, this watertight quad mesh is
# what the example project embeds as facets."""

if __name__ == "__main__":
    main()
